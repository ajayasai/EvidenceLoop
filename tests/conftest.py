"""Portable, isolated PostgreSQL fixtures with non-owner runtime credentials."""
from dataclasses import dataclass, field
import json
import os
from pathlib import Path
import re
from uuid import uuid4

import psycopg
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict, make_conninfo
import pytest

from scripts.migrate_db import migrate, MigrationError

ROOT=Path(__file__).resolve().parents[1]


@pytest.fixture(autouse=True)
def disable_real_inference(monkeypatch):
    """Routine tests must never consume a configured account's live quota."""
    monkeypatch.setenv("EVIDENCELOOP_LIVE_ENABLED", "false")
    monkeypatch.delenv("EVIDENCELOOP_MODEL_API_KEY", raising=False)


@dataclass(frozen=True)
class DatabaseURLs:
    admin: str=field(repr=False)
    app: str=field(repr=False)


@dataclass(frozen=True)
class IsolatedDatabase:
    url: str=field(repr=False)
    admin_url: str=field(repr=False)
    schema: str


@pytest.fixture(scope="session")
def test_database_urls():
    admin_url=os.environ.get("TEST_DATABASE_ADMIN_URL")
    app_url=os.environ.get("TEST_DATABASE_URL")
    if admin_url or app_url:
        if not admin_url or not app_url:
            pytest.fail("Set both TEST_DATABASE_ADMIN_URL and TEST_DATABASE_URL; an explicit test configuration may not silently skip integration tests.")
        return DatabaseURLs(admin_url,app_url)
    credentials=ROOT/".runtime/database-credentials.json"
    if credentials.exists():
        creds=json.loads(credentials.read_text())
        # Existing Windows bootstrap compatibility. CI and Linux use explicit URLs.
        return DatabaseURLs(
            make_conninfo(host="127.0.0.1",port="15432",dbname="evidenceloop",user="postgres",password=creds["admin"]),
            make_conninfo(host="127.0.0.1",port="15432",dbname="evidenceloop",user="evidenceloop_app",password=creds["app"]),
        )
    if os.environ.get("CI","").lower()=="true":
        pytest.fail("CI requires explicit test database URLs; integration tests cannot be skipped.")
    pytest.skip("Configure TEST_DATABASE_ADMIN_URL and TEST_DATABASE_URL, or run the local PostgreSQL bootstrap.")


@pytest.fixture
def isolated_database(test_database_urls):
    schema="el_test_"+uuid4().hex
    created=False
    try:
        try:
            with psycopg.connect(test_database_urls.admin,connect_timeout=5) as con:
                if con.execute("SELECT 1 FROM pg_namespace WHERE nspname=%s",(schema,)).fetchone():
                    raise MigrationError("Generated test schema unexpectedly exists")
            # This exact fresh UUID schema belongs to this fixture even if setup
            # commits its migration but later credential verification fails.
            created=True
            migrate(test_database_urls.admin,test_database_urls.app,schema,create_schema=True)
        except (MigrationError,psycopg.Error) as exc:
            pytest.fail(f"Could not prepare an isolated test schema ({type(exc).__name__}); credentials are not displayed.")
        parts=conninfo_to_dict(test_database_urls.app)
        # Only this generated schema is visible; preserve all other connection fields.
        parts["options"]="-csearch_path="+schema
        yield IsolatedDatabase(make_conninfo(**parts),test_database_urls.admin,schema)
    finally:
        if created:
            if not re.fullmatch(r"el_test_[0-9a-f]{32}",schema):
                raise RuntimeError("Refusing cleanup of a schema not generated by this fixture")
            with psycopg.connect(test_database_urls.admin,autocommit=True) as con:
                con.execute(sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(sql.Identifier(schema)))
